export type Clause = string | { text: string; items: string[] };

export interface Article {
  title: string;
  clauses: Clause[];
}

export interface LegalDocument {
  /** 시행일. 예) "2026년 10월 31일" */
  effectiveDate: string;
  /** 번호 매김. 약관은 "제1조", 방침처럼 조문이 아닌 문서는 "1." */
  numbering?: "article" | "section";
  /** 부칙 문장의 주어. 기본 "이 약관". */
  subject?: string;
  articles: Article[];
}

